#!/usr/bin/env python3
"""Assemble the main manuscript and the SI by inlining \\input{parts/...} / \\input{si_parts/...}."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "paper09_cod_certification_v44"

def inline(text, base):
    def rep(m):
        p = os.path.join(base, m.group(1))
        if not p.endswith(".tex"):
            p += ".tex"
        with open(p) as f:
            body = f.read()
        return inline(body, base)
    return re.sub(r"\\input\{([^}]+)\}", rep, text)

def build(parts_dir, order, out):
    chunks = []
    for name in order:
        with open(os.path.join(HERE, parts_dir, name)) as f:
            chunks.append(f.read().rstrip("\n") + "\n")
    text = inline("\n".join(chunks), HERE)
    with open(os.path.join(HERE, out), "w") as f:
        f.write(text)
    print("wrote", out, len(text.split("\n")), "lines")

MAIN = ["00_preamble.tex", "01_intro.tex", "02_frame.tex", "03_cod.tex", "04_edwards.tex", "05_synthesis.tex",
        "06_discussion.tex", "07_verification.tex", "08_related.tex", "09_conclusion.tex", "12_back.tex"]
SI = sorted(n for n in os.listdir(os.path.join(HERE, "si_parts")) if re.match(r"S\d", n) and n.endswith(".tex"))

def mainlabels():
    """write si_parts/S0b_mainlabels.tex from the main .aux (compile the main first)."""
    aux = os.path.join(HERE, f"{NAME}.aux")
    out = os.path.join(HERE, "si_parts", "S0b_mainlabels.tex")
    lines = ["% generated by assemble.py from the main .aux: label -> printed number"]
    if os.path.exists(aux):
        for m in re.finditer(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}", open(aux).read()):
            key, num = m.group(1), m.group(2)
            if key.endswith("@cref") or "." in key and key.startswith("sub@"):
                continue
            num = re.sub(r"\\relax", "", num)
            lines.append("\\mlabel{%s}{%s}" % (key, num))
    else:
        print("warning: main .aux not found; SI main-label references will be empty")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote si_parts/S0b_mainlabels.tex", len(lines) - 1, "labels")

if __name__ == "__main__":
    build("parts", MAIN, f"{NAME}.tex")
    if SI and "--main-only" not in sys.argv:
        mainlabels()
        build("si_parts", SI, f"{NAME}_SI.tex")
