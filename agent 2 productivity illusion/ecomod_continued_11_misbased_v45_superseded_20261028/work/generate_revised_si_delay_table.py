"""Generate a fresh SI delay/current-quality table for the revision draft.

These are revised-run outputs, not proof of the original C10 table's exact
historical run path. The main quality law is projected delayed quality; the
current-quality case is retained only as a sensitivity comparator.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "work"))
import twoland_fixed_projected as delayed
import twoland_fixed_current as current

TAUS = (5.0, 20.0, 40.0)
DT = 0.1
T_THRESHOLD = 800.0


def params(module, tau_g):
    return module.FixPara(
        rho_c=0.08, b_f0=0.85, b_c=0.05, b_Gc=0.80, alpha=0.03,
        eta_f=0.05, e=0.55, r=0.02, eta=0.05, tau_g=tau_g,
        tau_p=25.0, A_tot=2.5, deltab=1.0, t_wave=40.0,
        kappa_w=0.1, mu=0.06, tau_conv=1.0, chi_r=0.10,
    )


def floor_threshold(module, tau_g, A_c0=1.0):
    p = params(module, tau_g)

    def close_to_floor(P0):
        run = module.simulate(
            p, T=T_THRESHOLD, dt=DT, A_c0=A_c0, A_f0=0.6,
            q0=0.9, P0=P0,
        )
        return float(np.min(run["Ac"])) <= p.Ac_min + 1e-6

    lo, hi = 1.0, 5.0
    for _ in range(40):
        mid = 0.5 * (lo + hi)
        if close_to_floor(mid):
            hi = mid
        else:
            lo = mid
    return 0.5 * (lo + hi)


def demo_summaries(module, tau_g):
    p = params(module, tau_g)
    run = module.simulate(
        p, T=400.0, dt=0.05, A_c0=1.5, A_f0=0.6,
        q0=0.9, P0=1.2, E_fixed=0.825,
    )
    best, B, Ac, Af = module.longest_illusion(p, run)
    end = best[2] + 1
    ups0 = p.b_c + p.b_Gc * p.g_c(float(run["q"][0]))
    upse = p.b_c + p.b_Gc * p.g_c(float(run["q"][end]))
    cap0, cape = ups0 * float(Ac[0]), upse * float(Ac[end])
    fast0, faste = float(B[0]) - cap0, float(B[end]) - cape
    return {
        "window_yr": best[0] * run["dt"],
        "B_end_gha": float(B[end]),
        "Ac_end_ha": float(Ac[end]),
        "Af_end_ha": float(Af[end]),
        "capital_initial_gha": cap0,
        "capital_end_gha": cape,
        "fast_initial_gha": fast0,
        "fast_end_gha": faste,
    }


def main():
    models = {"current": current, "delayed": delayed}
    demo = {name: demo_summaries(mod, 20.0) for name, mod in models.items()}
    rows = []
    for tau_g in TAUS:
        row = {"tau_g_yr": tau_g, "dt_yr": DT, "T_threshold_yr": T_THRESHOLD}
        for name, mod in models.items():
            row[f"P0_{name}_cap"] = floor_threshold(mod, tau_g)
        rows.append(row)

    for name, summary in demo.items():
        if abs(summary["window_yr"] - (150.3 if name == "current" else 149.0)) > 0.15:
            raise AssertionError(f"unexpected {name} demonstration window: {summary['window_yr']}")

    out = ROOT / "output_revision_projected"
    out.mkdir(exist_ok=True)
    csv_path = out / "si_delay_sensitivity.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    # Values are emitted at the displayed precision; table identity and scope
    # are editorial decisions in si_01.tex, not generated by this script.
    # Keep row breaks explicit: a single backslash here is not a TeX row break.
    row_end = r" \\"
    body = [
        r"\begin{tabularx}{\textwidth}{>{\raggedright\arraybackslash}Xcc}",
        r"\toprule",
        r"Quantity & current $q(t)$ & projected delayed $q(t-\tau_g)$" + row_end,
        r"\midrule",
        rf"Demonstration window with $\dot B>0$, $\dot A_c<0$ (yr) & ${demo['current']['window_yr']:.1f}$ & ${demo['delayed']['window_yr']:.1f}$" + row_end,
        rf"Mask-end values $B$, $A_c$, $A_f$ & ${demo['current']['B_end_gha']:.3f},\ {demo['current']['Ac_end_ha']:.3f},\ {demo['current']['Af_end_ha']:.3f}$ & ${demo['delayed']['B_end_gha']:.3f},\ {demo['delayed']['Ac_end_ha']:.3f},\ {demo['delayed']['Af_end_ha']:.3f}$" + row_end,
        rf"Capital contribution $\Ups(q)A_c$ (initial $\to$ mask end, gha) & ${demo['current']['capital_initial_gha']:.5f}\to{demo['current']['capital_end_gha']:.5f}$ & ${demo['delayed']['capital_initial_gha']:.5f}\to{demo['delayed']['capital_end_gha']:.5f}$" + row_end,
        rf"Fast-land contribution $Y_f$ (initial $\to$ mask end, gha) & ${demo['current']['fast_initial_gha']:.5f}\to{demo['current']['fast_end_gha']:.5f}$ & ${demo['delayed']['fast_initial_gha']:.5f}\to{demo['delayed']['fast_end_gha']:.5f}$" + row_end,
    ]
    for row in rows:
        tau = int(row["tau_g_yr"])
        label = rf"$P_0$ floor threshold ($A_{{c0}}=1.0$\,ha, $\tau_g={tau}$\,yr, $\Delta t=0.1$\,yr)"
        body.append(
            rf"{label} & ${row['P0_current_cap']:.3f}$ & ${row['P0_delayed_cap']:.3f}$" + row_end
        )
    body.extend([r"\bottomrule", r"\end{tabularx}"])
    table_path = ROOT / "parts" / "si_tab_delay.tex"
    table_path.write_text("\n".join(body) + "\n", encoding="utf-8")

    print(f"wrote revised SI delay data: {csv_path}")
    print(f"wrote revised SI delay table body: {table_path}")
    for row in rows:
        print(row)
    for name, summary in demo.items():
        print(f"{name} demo: {summary}")


if __name__ == "__main__":
    main()
